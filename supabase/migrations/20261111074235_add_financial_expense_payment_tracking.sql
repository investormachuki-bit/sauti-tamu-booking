-- Payment ledger for partial settlement of operating expense records.
-- Applied to the existing Sauti Tamu Supabase project on 2026-11-11.

create table if not exists public.financial_expense_payments (
  id uuid primary key default gen_random_uuid(),
  expense_id uuid not null references public.expenses(id) on delete restrict,
  payment_date date not null default current_date,
  amount numeric not null check (amount > 0),
  payment_method public.payment_method not null default 'mpesa',
  reference text,
  notes text,
  idempotency_key uuid not null unique,
  created_at timestamptz not null default now()
);
create index if not exists financial_expense_payments_expense_date_idx on public.financial_expense_payments (expense_id,payment_date desc);
alter table public.financial_expense_payments enable row level security;
create policy financial_expense_payments_select_authenticated on public.financial_expense_payments for select to authenticated using (true);
create policy financial_expense_payments_insert_authenticated on public.financial_expense_payments for insert to authenticated with check (true);
grant select,insert on public.financial_expense_payments to authenticated;
grant all on public.financial_expense_payments to service_role;

create or replace function public.record_financial_expense_payment(
 p_expense_id uuid,p_amount numeric,p_payment_date date default current_date,
 p_payment_method public.payment_method default 'mpesa',p_reference text default null,
 p_notes text default null,p_idempotency_key uuid default gen_random_uuid()
) returns public.financial_expense_payments
language plpgsql security invoker set search_path = ''
as $$
declare v_expense public.expenses%rowtype; v_paid numeric; v_payment public.financial_expense_payments%rowtype;
begin
 if p_amount is null or p_amount<=0 then raise exception 'Payment amount must be greater than zero'; end if;
 select * into v_payment from public.financial_expense_payments where idempotency_key=p_idempotency_key;
 if found then return v_payment; end if;
 select * into v_expense from public.expenses where id=p_expense_id for update;
 if not found then raise exception 'Expense record not found'; end if;
 select coalesce(sum(amount),0) into v_paid from public.financial_expense_payments where expense_id=p_expense_id;
 if exists(select 1 from public.financial_obligation_payments where expense_id=p_expense_id) then raise exception 'This expense was generated by an obligation payment and is already settled'; end if;
 if p_amount>greatest(0,v_expense.amount-v_paid) then raise exception 'Payment exceeds the remaining expense balance'; end if;
 insert into public.financial_expense_payments(expense_id,payment_date,amount,payment_method,reference,notes,idempotency_key)
 values(p_expense_id,coalesce(p_payment_date,current_date),p_amount,coalesce(p_payment_method,'mpesa'::public.payment_method),nullif(trim(p_reference),''),nullif(trim(p_notes),''),p_idempotency_key)
 returning * into v_payment;
 return v_payment;
end;
$$;
revoke all on function public.record_financial_expense_payment(uuid,numeric,date,public.payment_method,text,text,uuid) from public,anon;
grant execute on function public.record_financial_expense_payment(uuid,numeric,date,public.payment_method,text,text,uuid) to authenticated;
